#!/usr/bin/env python3
"""Compare dart analyze output with a checked-in lint baseline.

Baseline format: '#' header lines, then sorted `<file>|<rule>=<count>` lines.
Counts are per (file, rule); line numbers are not part of the key, so moving
a finding does not churn the baseline.

Migration: a baseline written in the old format (whole finding lines copied
from analyzer output) is still read. read_baseline() detects those lines and
counts them with parse_findings(); the next --update rewrites the file in the
new format.
"""
import argparse, re, sys
from collections import Counter
from pathlib import Path

# Two analyzer formats. Old: `info • message • systematic_lints.<rule> • file:l:c • ...`.
# Dart 3.13: `   info - file.dart:9:25 - message - <rule>` (no prefix, rule id last).
# Deliberately matches any rule id, not a rule list.
FINDING_RE = re.compile(
    r"^\s*(?:error|warning|info)\s*[•:-].*\bsystematic_lints\.[a-z][a-z0-9_]*\b"
    r"|^\s*(?:error|warning|info)\s+-\s+\S+:\d+:\d+\s+-\s+.*\s-\s[a-z][a-z0-9_]*\s*$",
    re.I,
)
_OLD = re.compile(r"systematic_lints\.(?P<rule>[a-z][a-z0-9_]*)\b.*?\s(?P<path>\S+?):\d+:\d+")
_NEW = re.compile(r"^\s*\w+\s+-\s+(?P<path>\S+?):\d+:\d+\s+-\s+.*\s-\s+(?P<rule>[a-z][a-z0-9_]*)\s*$")

_HEADER = (
    "# lint_baseline.txt — generated by tool/lint_baseline.py --update\n"
    "# Findings that exist today, as <file>|<rule>=<count>. A file may have fewer, never more.\n"
    "# Regenerate only after a real reduction, and say so in the commit message.\n"
)


def findings(text):
    return [line.rstrip() for line in text.splitlines() if FINDING_RE.search(line)]


def parse_findings(text):
    """Count finding lines per 'path|rule' (path without :line:col)."""
    counts = Counter()
    for line in findings(text):
        m = _OLD.search(line) or _NEW.match(line)
        if m:
            counts[f"{m['path']}|{m['rule']}"] += 1
    return dict(counts)


def format_baseline(counts):
    return _HEADER + "".join(f"{k}={v}\n" for k, v in sorted(counts.items()))


def read_baseline(text):
    if findings(text):  # old whole-line format: migrate by counting
        return parse_findings(text)
    out = {}
    for line in text.splitlines():
        if not line.strip() or line.startswith("#"):
            continue
        key, _, value = line.rpartition("=")
        out[key] = int(value)
    return out


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument('--baseline')
    ap.add_argument('--require-any', action='store_true',
                    help='fail unless at least one finding line is recognised')
    ap.add_argument('--update', action='store_true')
    ap.add_argument('input', nargs='?', help='analyzer output (default: stdin)')
    args = ap.parse_args(argv)
    text = Path(args.input).read_text() if args.input else sys.stdin.read()
    if args.require_any:
        if not findings(text):
            print('no finding lines recognised in analyzer output (format changed?)', file=sys.stderr)
            return 1
        return 0
    if not args.baseline:
        ap.error('--baseline is required')
    base_path = Path(args.baseline)
    current = parse_findings(text)
    if args.update:
        base_path.parent.mkdir(parents=True, exist_ok=True)
        base_path.write_text(format_baseline(current))
        return 0
    baseline = read_baseline(base_path.read_text()) if base_path.exists() else {}
    bad = []
    for key, count in sorted(current.items()):
        allowed = baseline.get(key, 0)
        if count > allowed:
            path, rule = key.split('|')
            bad.append(f"{path}: {rule} {count} (baseline allows {allowed})")
    if bad:
        print('New systematic_lints findings:', file=sys.stderr)
        print('\n'.join(bad), file=sys.stderr)
        return 1
    for key, allowed in sorted(baseline.items()):
        now = current.get(key, 0)
        if now < allowed:
            path, rule = key.split('|')
            print(f"improvement: {path} {rule} {allowed} -> {now}")
    if any(current.get(k, 0) < v for k, v in baseline.items()):
        print('Findings went down. Rewrite the baseline with: python3 tool/lint_baseline.py --baseline <baseline> --update <analyzer-output>.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
